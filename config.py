# =============================================================================
# config.py — 학습 전체에서 공유되는 하이퍼파라미터 및 설정값 모음
#
# 이 파일에 숫자를 한 곳에 모아두면,
#   "학습 속도가 너무 빠르다"  → LEARNING_RATE 를 줄이면 됩니다.
#   "탐험을 더 많이 하고 싶다" → EPSILON_START 를 높이면 됩니다.
# 코드 여러 파일을 뒤질 필요 없이 이 파일 하나만 수정하면 됩니다.
# =============================================================================

# ── 학습 횟수 ──────────────────────────────────────────────────────────────
# 에피소드(episode) = 게임 한 판
# 두 로봇이 총 몇 판 대결하면서 학습할지 결정합니다.
NUM_EPISODES = 500_000

# ── Q-러닝 핵심 파라미터 ──────────────────────────────────────────────────
# LEARNING_RATE (알파, α):
#   새로운 정보를 기존 지식에 얼마나 빠르게 반영할지 결정합니다.
#   0에 가까울수록 천천히 배우고, 1에 가까울수록 최근 결과에만 의존합니다.
#   일반적으로 0.1 ~ 0.5 사이가 적당합니다.
LEARNING_RATE = 0.3

# DISCOUNT_FACTOR (감마, γ):
#   미래 보상을 현재 기준으로 얼마나 할인할지 결정합니다.
#   1에 가까울수록 먼 미래의 보상도 중요하게 여깁니다.
#   틱택토처럼 짧은 게임에서는 0.9~0.99가 적합합니다.
DISCOUNT_FACTOR = 0.95

# ── 탐험(Exploration) vs 활용(Exploitation) ───────────────────────────────
# 로봇이 학습 초기에는 무작위로 움직이며 다양한 상황을 경험(탐험)하고,
# 학습이 진행될수록 쌓인 지식을 활용(활용)하도록 ε(epsilon)을 조절합니다.

# EPSILON_START: 처음에는 100% 무작위 행동
EPSILON_START = 1.0

# EPSILON_END: 학습이 끝날 때 최소 탐험 비율 (완전히 0으로 하지 않아
#              이미 학습한 후에도 약간의 탐험을 유지해 과적합을 방지)
EPSILON_END = 0.05

# EPSILON_DECAY: 매 에피소드마다 ε 을 이 비율로 줄여 나갑니다.
#   500,000 판 학습 시 약 10만 판 이후부터 주로 활용 위주로 전환됩니다.
EPSILON_DECAY = 0.99995

# ── 보상값 (Reward Values) ────────────────────────────────────────────────
# 보상 설계 철학:
#   승리 = 최대 양수, 패배 = 최대 음수, 무승부 = 작은 양수,
#   잘못된 수(이미 채워진 칸) = 강한 음수 패널티
#
# 무승부를 작은 양수(+0.3)로 준 이유:
#   무승부와 패배 모두 0으로 설정하면 로봇이 지는 것에 무감각해집니다.
#   무승부 > 패배 임을 명확히 알려줘서 "지느니 비기겠다"는 전략을 자연스럽게 학습합니다.
REWARD_WIN   =  1.0   # 이겼을 때: 강한 양의 보상
REWARD_LOSE  = -1.0   # 졌을 때:   강한 음의 보상
REWARD_DRAW  =  0.3   # 비겼을 때: 작은 양의 보상 (패배보다 낫다는 신호)
REWARD_STEP  =  0.0   # 게임 진행 중 각 수: 중립 (불필요한 보상 편향 방지)
REWARD_INVALID = -0.5 # 이미 채워진 칸에 두려 할 때: 음의 패널티

# ── 모델 저장 경로 ────────────────────────────────────────────────────────
# 학습된 Q-테이블을 파일로 저장해두면, 다음에 처음부터 다시 배울 필요가 없습니다.
MODEL_DIR        = "models"
MODEL_PATH_O     = f"{MODEL_DIR}/agent_O.pkl"  # O 로봇의 두뇌 파일
MODEL_PATH_X     = f"{MODEL_DIR}/agent_X.pkl"  # X 로봇의 두뇌 파일

# ── 로그·출력 주기 ────────────────────────────────────────────────────────
# 학습 진행 상황을 몇 판마다 한 번씩 출력할지 결정합니다.
LOG_INTERVAL = 10_000
